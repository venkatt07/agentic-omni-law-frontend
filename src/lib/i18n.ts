function interpolate(template: string, params?: TranslationParams) {
  if (!params) return template;
  return Object.entries(params).reduce(
    (resolved, [key, value]) => resolved.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function translate(language: string, key: string, params?: TranslationParams) {
  const resolvedLanguage: SupportedLanguage = isSupportedLanguage(language) ? language : "English";
  const dictionary = translations[resolvedLanguage] || translations.English;
  const template = dictionary[key] || translations.English[key] || key;
  return interpolate(template, params);
}

function normalizeLanguageName(language?: string | null): SupportedLanguage {
  return isSupportedLanguage(String(language || "")) ? (language as SupportedLanguage) : "English";
}

