const reversePhraseCache = new Map<SupportedLanguage, Array<[string, string]>>();

function stripSyntheticLanguagePrefix(text: string) {
  return text.replace(/^\[(?:Hindi|Tamil|Bengali)\]\s*/i, "").trimStart();
}

function getReversePhrasePairs(language: SupportedLanguage) {
  const cached = reversePhraseCache.get(language);
  if (cached) return cached;
  const targetDictionary = translations[language] || translations.English;
  const pairs = Object.entries({
    ...Object.fromEntries(
      Object.keys(english).map((key) => [english[key], targetDictionary[key] || translations.English[key] || english[key]]),
    ),
    ...fallbackUiPhrases[language],
  })
    .filter(([from, to]) => from && to && from !== to)
    .sort((a, b) => b[0].length - a[0].length);
  reversePhraseCache.set(language, pairs);
  return pairs;
}

export function autoTranslateUiText(input: string, language?: string) {
  const target = normalizeLanguageName(language);
  const text = stripSyntheticLanguagePrefix(String(input || ""));
  if (target === "English") return text;
  if (!/[A-Za-z]/.test(text)) return text;
  if (/^(https?:\/\/|\/|[A-Za-z0-9_-]{8,}|[0-9]+%?)$/.test(text.trim())) return text;
  let output = text;
  for (const [from, to] of getReversePhrasePairs(target)) {
    output = output.replaceAll(from, to);
  }
  for (const [from, to] of Object.entries(fallbackUiWords[target])) {
    output = output.replace(new RegExp(`\\b${from}\\b`, "g"), to);
  }
  for (const [from, to] of Object.entries(fallbackUiWordOverrides[target])) {
    output = output.replace(new RegExp(`\\b${from}\\b`, "g"), to);
  }
  return output;
}
